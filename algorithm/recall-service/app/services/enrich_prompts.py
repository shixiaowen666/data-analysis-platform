# -*- coding: utf-8 -*-
"""
enrich_prompts —— 元数据 AI 补全的 4 个默认模板（v2 全局上下文版）

设计原则：
- 输入全量：每类目标的 prompt 都包含全库上下文（全部表/维度/指标），模型通读全局后统一输出
- 占位符用 {name} 单花括号，meta_enricher._fmt 做纯文本替换，模板里可自由写 JSON 花括号
- 输出仅 JSON：{"items":[...]}，由 LLMClient.generate_json 解析

注册到 prompt_manager 后可在页面"提示词管理"在线编辑，改完即生效。
"""

ENRICH_METRIC_PROMPT = """# 角色
你是电网数据仓库的元数据治理专家。下面给出**全库**的表清单、维度清单、指标清单，请先通读全局，再为指标生成 description。

# 全局上下文
## 全部表（表名 / 中文名 / 用途）
{tables}

## 全部维度（code / 名称 / 描述）
{dimensions}

## 全部指标（code / 名称 [单位] / 现有描述）
{metrics}

# 任务
为**本片指定的指标**逐条生成 description。

{output_scope}

# 生成要求
1. 描述 = 业务含义 + 单位 + 统计口径，**硬性上限 50 字**（超过会被程序直接丢弃），一句话，中文
2. 单位优先用清单中已标注的；缺失时按业务常识推断（电量为亿/万千瓦时，次数为次，比率为%），无法推断则不写单位
3. **全局视角**：同类指标（如各局电量、各电压等级、同比/环比类）描述必须突出彼此差异，禁止雷同句式复述名称
4. 禁止以"该指标""此字段"开头，禁止复述 code
5. 同表其他字段仅供理解口径，不要罗列进描述
6. 同名指标（跨表复用）必须使用完全相同的描述

# 输出（仅 JSON，不要任何其他文字）
{"items":[{"code":"指标code","description":"..."}]}
items 必须覆盖 output_scope 中的每一个 code，不得增删。
"""

ENRICH_DIM_PROMPT = """# 角色
你是电网数据仓库的元数据治理专家。下面给出**全库**的表清单、指标清单、维度清单，请先通读全局，再为维度生成 description。

# 全局上下文
## 全部表（表名 / 中文名 / 用途）
{tables}

## 全部指标（code / 名称 [单位] / 现有描述）
{metrics}

## 全部维度（code / 名称 / 现有描述 / 取值样例）
{dimensions}

# 任务
为全部 {dim_count} 个维度生成 description（输入全量，输出按片进行）。

{output_scope}

# 生成要求
1. 描述 = 业务含义 + 典型过滤用法，**硬性上限 30 字**（超过会被程序直接丢弃），一句话，中文
2. 有取值样例的说明取值特点（如"供电分局全称，约10个取值"），**禁止罗列维度值**
3. **全局视角**：组织类维度（供电局/区局/分局/编号等）要写清层级与相互区别；时间类维度（日期/月/季/周/年）写清粒度
4. **同名或同义的维度（跨表复用）必须使用完全相同的描述**；名称不同但含义相同的（如 ptdate 与日期字段）也要保持一致
5. 禁止以"该维度""此字段"开头

# 输出（仅 JSON，不要任何其他文字）
{"items":[{"code":"维度code","description":"..."}]}
items 必须覆盖 output_scope 中的每一个 code，不得增删。
"""

ENRICH_TABLE_PROMPT = """# 角色
你是电网数据仓库的元数据治理专家。下面给出**全库** {table_count} 张表的字段清单和指标维度清单，请先通读全局，再为每张表生成 description。

# 全部表及字段（表名 / 中文名 / 用途，字段: 字段名(中文名,角色)）
{tables}

# 指标与维度全局清单（用于理解字段业务含义）
{metrics_and_dimensions}

# 任务
为全部 {table_count} 张表生成 description（输入全量，输出按片进行）。

{output_scope}

# 生成要求
1. 描述 = 业务主题 + 数据粒度（一行记录代表什么）+ 典型查询场景，**硬性上限 100 字**（超过会被程序直接丢弃）
2. 依据字段清单推断业务主题；**禁止罗列字段名**
3. **全局视角**：多张相似表（如多张供电量/线损/工单类表）必须写清彼此区别（口径、粒度、来源不同），这是本次生成最重要的价值
4. 以表的中文名开头

# 输出（仅 JSON，不要任何其他文字）
{"items":[{"table_name":"表名","description":"..."}]}
items 必须覆盖 output_scope 中的每一个 table_name，不得增删。
"""

ENRICH_ALIAS_PROMPT = """# 角色
你是电网数据仓库的业务分析师。下面给出全部业务知识条目和全库指标维度名称，请先通读，再为每条知识提炼检索别名。

# 全库指标与维度名称（供参考，别名风格与用词应与之一致）
{names}

# 业务知识条目（编号. 正文）
{knowledge}

# 任务
为每条知识提炼 knowledgeAlias（检索别名数组，输入全量，输出按片进行）。

{output_scope}

# 生成要求
1. 每条 2~6 个别名：同义词、简称、用户口语说法（如"上周""全市""区局范围""组织机构"）
2. 别名是 2~8 字短词，不是句子；禁止照抄正文长片段
3. 覆盖正文【】标签里的核心词（不含【】符号本身）
4. 参考全库名称用词，保证用户提问的措辞能命中

# 输出（仅 JSON，不要任何其他文字）
{"items":[{"id":条目编号,"aliases":["别名1","别名2"]}]}
items 必须覆盖 output_scope 中的每一个编号，不得增删。
"""

